export function resolveAssetUrl(url: string): string {
  if (!url) return url;
  return ASSET_PATH_MAP[url] ?? url;
}

export function resolveAssetTree<T>(input: T): T {
  if (typeof input === 'string') {
    return resolveAssetUrl(input) as unknown as T;
  }
  if (Array.isArray(input)) {
    return input.map((item) => resolveAssetTree(item)) as unknown as T;
  }
  if (input && typeof input === 'object') {
    const out: Record<string, any> = {};
    for (const [k, v] of Object.entries(input)) {
      if (k === '__proto__' || k === 'constructor' || k === 'prototype') {
        continue;
      }
      out[k] = resolveAssetTree(v);
    }
    return out as T;
  }
  return input;
}
